# Buat program untuk perulangan for dalam python
# Nama variabel ditambah 4 digit nim terakhir contoh: ulang_1012
# program ini menggunakan fungsi input()

ulang_1012 = int(input("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_1012-1)
for i_1012 in range(ulang_1012):
    print(i_1012, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_1012)
for i_1012 in range(1, ulang_1012+1):
    print(i_1012, end=" ")