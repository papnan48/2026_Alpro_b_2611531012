batas_1012 = int(input("Masukkan nilai batas: "))
for i_1012 in range(batas_1012 + 1):
    for j_1012 in range(batas_1012 + 1):
        print(i_1012 + j_1012, end=" ")
    print() # pindah ke baris berikutnya