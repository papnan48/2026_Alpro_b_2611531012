nilai_1012 = int(input("Inputkan nilai angka= "))

if nilai_1012 >= 81:
    print("A")
elif nilai_1012 >= 70:
    print("B")
elif nilai_1012 >= 60:
    print("C")
elif nilai_1012 >= 50:
    print("D")
else:
    print("E")